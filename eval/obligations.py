"""Obligation-level review and regression baseline.

    python eval/obligations.py                 # show the duty set per case
    python eval/obligations.py --freeze        # write the reviewed baseline
    python eval/obligations.py --check         # fail on any drift from it
    python eval/obligations.py --set holdout

WHY THIS EXISTS

The eval scored facts. The client receives an OBLIGATION LIST. Nothing measured
the thing actually handed over, which means a correct ANNEX_III tier that
silently drops the Art. 27 FRIA scored as a flawless result while being a failed
audit.

This runs offline on the LABELLED facts, so it isolates the rule engine from
fact extraction: any difference here is the engine's reading of the law, not the
model misreading a description. Two uses:

  --freeze   writes eval/obligation_baseline.json, keyed "role:article". That
             file is the artefact a lawyer can review WITHOUT reading the
             schema — the first external check this project can actually buy.
             Review it, then commit it.

  --check    compares the engine against the reviewed baseline and fails on any
             drift. Once counsel has signed off on a duty set, a refactor that
             quietly drops Art. 26(6) stops being a silent regression.

Duties are keyed by the role that owes them: "deployer:Art. 27" and
"provider:Art. 27" are different claims about the law and must not collapse.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from eval.score import obligation_keys, score_obligations  # noqa: E402
from rules import classify  # noqa: E402
from schema import Facts  # noqa: E402

SETS = {
    "golden": Path(__file__).parent / "golden_set.json",
    "holdout": Path(__file__).parent / "holdout_set.json",
}
BASELINE = Path(__file__).parent / "obligation_baseline.json"


def duties_for(case: dict) -> dict:
    """Run the engine on the case's LABELLED facts — no API, no extraction."""
    a = classify(Facts.model_validate(case["expected"]), case["name"])
    return {
        "id": case["id"],
        "tier": a.tier,
        "roles": sorted(a.roles),
        "duties": sorted(obligation_keys(a)),
    }


def freeze(cases: list[dict], which: str) -> int:
    current = json.loads(BASELINE.read_text(encoding="utf-8")) if BASELINE.exists() else {}
    current[which] = {d["id"]: d for d in (duties_for(c) for c in cases)}
    current["_readme"] = (
        "Reviewed obligation baseline, keyed 'role:article'. Generated by "
        "eval/obligations.py --freeze from the LABELLED facts, so it reflects the "
        "rule engine's reading of the law rather than fact extraction. Have "
        "counsel review this file, then commit it; --check fails on any drift.")
    BASELINE.write_text(json.dumps(current, indent=2, sort_keys=True), encoding="utf-8")
    n = len(current[which])
    total = sum(len(v["duties"]) for v in current[which].values())
    print(f"Froze {n} cases ({total} duties) for '{which}' -> {BASELINE}")
    print("Review this file — ideally with counsel — then commit it.")
    return 0


def check(cases: list[dict], which: str) -> int:
    if not BASELINE.exists():
        print(f"No baseline at {BASELINE}. Run --freeze first.")
        return 1
    baseline = json.loads(BASELINE.read_text(encoding="utf-8")).get(which, {})
    if not baseline:
        print(f"No baseline entries for set '{which}'. Run --freeze --set {which}.")
        return 1

    drifted, unknown = [], []
    for case in cases:
        now = duties_for(case)
        was = baseline.get(now["id"])
        if was is None:
            unknown.append(now["id"])
            continue
        s = score_obligations(set(was["duties"]), set(now["duties"]))
        if not s["exact"] or was["tier"] != now["tier"]:
            drifted.append((now["id"], was, now, s))

    print("=" * 74)
    print(f"OBLIGATION BASELINE — {len(cases)} cases in '{which}'")
    print("=" * 74)
    for cid, was, now, s in drifted:
        print(f"\n  DRIFT {cid}")
        if was["tier"] != now["tier"]:
            print(f"    tier    {was['tier']} -> {now['tier']}")
        for d in s["missing"]:
            print(f"    DROPPED {d}   (duty the baseline says is owed)")
        for d in s["extra"]:
            print(f"    ADDED   {d}")
    if unknown:
        print(f"\n  {len(unknown)} case(s) not in the baseline: {', '.join(unknown[:6])}")
        print("    Run --freeze to add them (and review the result).")
    if not drifted and not unknown:
        print("  no drift — the engine matches the reviewed baseline")
    return 1 if (drifted or unknown) else 0


def show(cases: list[dict]) -> int:
    rows = [duties_for(c) for c in cases]
    total = sum(len(r["duties"]) for r in rows)
    print("=" * 74)
    print(f"DUTY SETS — {len(rows)} cases, {total} duties, "
          f"{total / (len(rows) or 1):.1f} per case")
    print("=" * 74)
    for r in rows:
        print(f"\n  {r['id']}  [{r['tier']}]  roles={'+'.join(r['roles'])}")
        by_role: dict[str, list[str]] = {}
        for d in r["duties"]:
            role, _, art = d.partition(":")
            by_role.setdefault(role, []).append(art)
        for role, arts in sorted(by_role.items()):
            print(f"      {role:12} {', '.join(arts)}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--set", dest="which", choices=sorted(SETS), default="golden")
    ap.add_argument("--freeze", action="store_true", help="write the reviewed baseline")
    ap.add_argument("--check", action="store_true", help="fail on drift from the baseline")
    args = ap.parse_args()

    cases = json.loads(SETS[args.which].read_text(encoding="utf-8"))["cases"]
    if args.freeze:
        return freeze(cases, args.which)
    if args.check:
        return check(cases, args.which)
    return show(cases)


if __name__ == "__main__":
    raise SystemExit(main())
